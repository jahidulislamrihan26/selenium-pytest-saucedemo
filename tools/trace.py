"""Builds docs/traceability.md: which cases of the manual test suite (manual-testing-saucedemo repository) this project automates.

A test is linked to a manual case by `@manual("TC-nnn")` (or `marks=manual("TC-nnn")` inside a parametrized list) and to a defect by
`BUG-nnn` in its xfail reason. A case counts as a known-defect case when the decorators of its test contain an xfail marker.
Usage: python tools/trace.py        (standard library only)
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TESTS = ROOT / "tests"
TC = re.compile(r"TC-\d{3}")
BUG = re.compile(r"BUG-\d{3}")

with open(ROOT / "data" / "manual-test-cases.csv", encoding="utf-8-sig", newline="") as fh:
    manual = [{"id": r["ID"], "title": r["Title"], "status": r["Status"], "defect": r["Defect"]} for r in csv.DictReader(fh)]

hits: dict[str, list[dict]] = {}
definitions = 0
for path in sorted(TESTS.glob("test_*.py")):
    lines = path.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        if re.match(r"\s*def test_", line):
            definitions += 1
        if line.lstrip().startswith("#"):
            continue
        for tc in TC.findall(line):
            # the decorators of the test: from this line forward to the next function definition
            j = i
            while j < len(lines) and not re.match(r"\s*def ", lines[j]):
                j += 1
            block = "\n".join(lines[i:j])
            hits.setdefault(tc, []).append({
                "file": path.name, "line": i + 1,
                "known": "xfail" in block,
                "bug": (BUG.findall(block) or [None])[0],
            })

manual_ids = {m["id"] for m in manual}
unknown = sorted(set(hits) - manual_ids)
rows = []
for m in manual:
    found = hits.get(m["id"], [])
    state = "Manual only" if not found else ("Automated, known defect" if all(h["known"] for h in found) else "Automated")
    rows.append({**m, "hits": found, "state": state})
count = lambda s: sum(1 for r in rows if r["state"] == s)
automated = count("Automated") + count("Automated, known defect")
defects = {h["bug"] for found in hits.values() for h in found if h["bug"]}

out = [
    "# Traceability: manual test cases to Selenium tests", "",
    "Generated by `python tools/trace.py` from the manual suite ([test-cases.csv](https://github.com/jahidulislamrihan26/manual-testing-saucedemo/blob/main/test-suite/test-cases.csv), snapshot in data/manual-test-cases.csv) and the test files. A test is linked to a manual case by `@manual(\"TC-nnn\")` and to a defect by `BUG-nnn` in its xfail reason.", "",
    f"**{automated} of {len(rows)} manual cases ({round(100 * automated / len(rows))}%) have at least one Selenium test.** {len(defects)} of the 20 logged defects are captured as known-defect tests.", "",
    "| Result | Manual cases |", "|---|---|",
    f"| Automated (passing check) | {count('Automated')} |",
    f"| Automated, captures a known defect | {count('Automated, known defect')} |",
    f"| Manual only | {count('Manual only')} |", "",
    "| Manual case | Title | Manual result | Automated | Where |", "|---|---|---|---|---|",
]
for r in rows:
    where = ", ".join(f"{h['file']}:{h['line']}" for h in r["hits"][:3]) + (f", +{len(r['hits']) - 3} more" if len(r["hits"]) > 3 else "")
    bugs = sorted({h["bug"] for h in r["hits"] if h["bug"]})
    out.append(f"| {r['id']} | {r['title'].replace('|', chr(92) + '|')} | {r['status']}{' (' + r['defect'] + ')' if r['defect'] else ''} | {r['state']}{' ' + ', '.join(bugs) if bugs else ''} | {where if r['hits'] else '-'} |")
manual_only = [r for r in rows if r["state"] == "Manual only"]
out += ["", "## Manual only, and why", "",
        "These cases are covered by the other projects for the same site (the [Playwright project](https://github.com/jahidulislamrihan26/playwright-ui-automation-pom) automates most of them) or need a human eye:", ""]
out += [f"- **{r['id']}** {r['title']}" for r in manual_only]
if unknown:
    out += ["", f"**Warning:** these ids appear in tests but not in the manual suite: {', '.join(unknown)}"]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "traceability.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"Traceability: {automated}/{len(rows)} cases automated, {len(defects)} defects covered, {definitions} test functions, {len(manual_only)} manual only" + (f", WARNING unknown ids: {', '.join(unknown)}" if unknown else ""))
